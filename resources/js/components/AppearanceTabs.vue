            v-for="{ value, Icon, label } in tabs"
            :key="value"
            @click="updateAppearance(value)"
            :class="[
                'flex min-w-0 items-center justify-center rounded-md px-2 py-1.5 transition-colors sm:px-3.5',
                appearance === value
